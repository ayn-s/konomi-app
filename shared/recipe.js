// 必ず選ぶ項目と、選ばなければおまかせの項目
export const REQUIRED = Object.keys(D).filter(k => !D[k].optional);
export const OPTIONAL = Object.keys(D).filter(k => D[k].optional);

// 選ばれていないおまかせの項目に、ランダムな値を入れる(画面で調合する直前に使う)
export function fillOptional(sel) {
  const out = { ...sel };
  for (const k of OPTIONAL) {
    if (!out[k]) { const keys = Object.keys(D[k].o); out[k] = keys[Math.floor(Math.random() * keys.length)]; }
  }
  return out;
}

// 選んだ項目から、飲み物の名前・色・配合・見た目を決める
// s = { c, t, w, h, p, m, v, s }  a = からだの材料の割合(%)。省略するとランダム
// 同じ s と a なら必ず同じ結果になる(サーバーで作り直して確かめるため)
export function makeRecipe(s, a = 45 + Math.floor(Math.random() * 10)) {
  const cd = D.c.o[s.c], td = D.t.o[s.t], wd = D.w.o[s.w], hd = D.h.o[s.h];
  const pd = D.p.o[s.p], md = D.m.o[s.m], sd = D.s.o[s.s];
  let vd = D.v.o[s.v];
  if (vd.auto) { const fixed = Object.values(D.v.o).filter(x => !x.auto); vd = fixed[a % fixed.length]; } // おまかせの量
  const temp = pd || td;   // のみたい温度を選んでいればそちら、なければ体感の気温から
  const l = temp.l;
  const b = 80 - a;
  return {
    sel: { ...s }, a,
    name: `${wd.pre}${cd.ing}・${hd.s}`,
    text: `${temp.w}${vd.w}一本です。${cd.msg}${md.msg}${sd.msg}`,
    colors: {
      top: `hsl(${hd.h} 85% ${l + 14}%)`,
      bottom: `hsl(${cd.h} 75% ${l - 6}%)`,
      bit1: `hsl(${cd.h} 80% 78%)`,
      bit2: `hsl(${hd.h} 85% 82%)`,
      mood: `hsl(${md.h} 90% 72%)`,
      mixC: `hsl(${cd.h} 75% 60%)`,
      mixH: `hsl(${hd.h} 85% 66%)`
    },
    look: { size: vd.size, ice: temp.ice || 0, fizz: sd.fizz },
    mix: [
      { label: wd.base, pct: 20, color: "#a9c4dc" },
      { label: cd.ing, pct: a },
      { label: hd.ing, pct: b }
    ]
  };
}
